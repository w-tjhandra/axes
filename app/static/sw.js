/* Service worker: app shell offline-first, API network-first. */
const CACHE_NAME = 'ukk-jnt-v25';
const APP_SHELL = [
  '/',
  '/index.html',
  '/app.css?v=19',
  '/app.js?v=25',
  '/favicon.svg?v=19',
  '/manifest.webmanifest?v=19',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Data penilaian tidak boleh dilayani dari cache.
  if (url.pathname.startsWith('/api/') || url.pathname === '/healthz' || url.pathname === '/robots.txt') {
    event.respondWith(fetch(request));
    return;
  }

  // Navigasi hash tidak mengirim request baru; untuk path lain pakai shell.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put('/index.html', copy));
          return response;
        })
        .catch(() => caches.match('/index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (!response || response.status !== 200 || response.type !== 'basic') return response;
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      });
    })
  );
});
